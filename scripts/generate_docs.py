"""Generate and verify auto-synced Ether configuration and tool catalog documentation."""

from __future__ import annotations

import argparse
import sys
import tomllib
from pathlib import Path
from typing import Any, Dict, List

ROOT = Path(__file__).resolve().parent.parent
SRC_DIR = ROOT / "src"
if str(SRC_DIR) not in sys.path:
    sys.path.insert(0, str(SRC_DIR))

from ether.config import EtherSettings  # noqa: E402
from ether.registry.manifest import Manifest  # noqa: E402

CONFIG_DOC_PATH = ROOT / "docs" / "reference" / "configuration.md"
TOOLS_DOC_PATH = ROOT / "docs" / "reference" / "tools-catalog.md"

_LEGACY_ENV_OVERRIDES = {
    ("paths", "data_dir"): "ETHER_DATA_DIR",
    ("paths", "wordlists_dir"): "ETHER_WORDLISTS_DIR",
    ("mcp", "auth_token"): "ETHER_MCP_AUTH_TOKEN",
    ("graph", "onnx_model_path"): "ETHER_ONNX_MODEL_PATH",
    ("execution", "container_fallback"): "ETHER_CONTAINER_FALLBACK",
    ("execution", "container_image"): "ETHER_CONTAINER_IMAGE",
    ("logging", "debug"): "ETHER_DEBUG",
    ("registry", "trust_mode"): "ETHER_PLUGIN_TRUST_MODE",
}


def render_configuration_doc() -> str:
    """Render docs/reference/configuration.md from EtherSettings."""
    lines: List[str] = [
        "<!-- AUTO-GENERATED by scripts/generate_docs.py — DO NOT EDIT MANUALLY -->",
        "# Ether Configuration & Settings Reference",
        "",
        "Ether unifies all runtime, security, storage, MCP, and execution options in `EtherSettings` (`src/ether/config.py`).",
        "",
        "## Precedence Order",
        "1. **CLI flags** (`--data-dir`, `--db`, `--tools`, `--policy`, `--config`, `--verbose`, `--json`)",
        "2. **Environment variables** (`ETHER_<SECTION>__<FIELD>` or legacy `ETHER_*` aliases)",
        "3. **Config file** (`$ETHER_DATA_DIR/config.toml` or `~/.ether/config.toml`)",
        "4. **Built-in defaults**",
        "",
        "Inspect active settings at any time with:",
        "```bash",
        "ether config show --json",
        "ether config path",
        "```",
        "",
    ]

    for sec_name, sec_field in EtherSettings.model_fields.items():
        sec_model = sec_field.annotation
        lines.append(f"## `[{sec_name}]`")
        if getattr(sec_model, "__doc__", None):
            lines.append(sec_model.__doc__.strip())
            lines.append("")
        lines.append("| Key | Default | Env Override | Description |")
        lines.append("| :--- | :--- | :--- | :--- |")
        for fname, finfo in sec_model.model_fields.items():
            default_repr = f"`{finfo.default!r}`" if finfo.default_factory is None else "`[]`"
            env_var = _LEGACY_ENV_OVERRIDES.get(
                (sec_name, fname), f"ETHER_{sec_name.upper()}__{fname.upper()}"
            )
            desc = (finfo.description or "").replace("|", "\\|")
            lines.append(f"| `{fname}` | {default_repr} | `{env_var}` | {desc} |")
        lines.append("")

    return "\n".join(lines)


def render_tools_catalog_doc() -> str:
    """Render docs/reference/tools-catalog.md from tools/*/manifest.toml."""
    lines: List[str] = [
        "<!-- AUTO-GENERATED by scripts/generate_docs.py — DO NOT EDIT MANUALLY -->",
        "# Ether Security Tools Catalog",
        "",
        "All registered tool adapters, execution tiers, input/output schemas, and executable `[profiles]`.",
        "",
        "Fast execution:",
        "```bash",
        "ether tool search nmap",
        "ether run nmap 10.0.0.1 --profile fast --json",
        "```",
        "",
        "| Tool | Tier | Accepts | Produces | Profiles | Timeout (s) |",
        "| :--- | :--- | :--- | :--- | :--- | :--- |",
    ]

    tools_dir = ROOT / "tools"
    for tool_path in sorted(tools_dir.iterdir(), key=lambda p: p.name):
        manifest_path = tool_path / "manifest.toml"
        if not (tool_path.is_dir() and manifest_path.is_file()):
            continue
        with open(manifest_path, "rb") as f:
            data: Dict[str, Any] = tomllib.load(f)
        manifest = Manifest(**data)
        meta = manifest.meta
        accepts = ", ".join(manifest.input.get("accepts", [])) or "-"
        produces = ", ".join(manifest.output.get("produces", [])) or "-"
        profiles = ", ".join(sorted((manifest.profiles or {}).keys())) or "-"
        timeout = manifest.execution.default_timeout_sec
        lines.append(
            f"| `{meta.name}` | `{meta.execution_tier}` | {accepts} | {produces} | `{profiles}` | `{timeout}` |"
        )

    lines.append("")
    return "\n".join(lines)


def main(argv: List[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate or verify Ether reference docs.")
    parser.add_argument("--check", action="store_true", help="Exit non-zero if docs are out of sync.")
    args = parser.parse_args(argv)

    cfg_text = render_configuration_doc()
    tools_text = render_tools_catalog_doc()

    if args.check:
        ok = True
        for path, expected in ((CONFIG_DOC_PATH, cfg_text), (TOOLS_DOC_PATH, tools_text)):
            if not path.is_file() or path.read_text(encoding="utf-8") != expected:
                print(f"[OUT OF SYNC] {path.relative_to(ROOT)}", file=sys.stderr)
                ok = False
        return 0 if ok else 1

    CONFIG_DOC_PATH.parent.mkdir(parents=True, exist_ok=True)
    CONFIG_DOC_PATH.write_text(cfg_text, encoding="utf-8")
    TOOLS_DOC_PATH.write_text(tools_text, encoding="utf-8")
    print(f"Generated {CONFIG_DOC_PATH.relative_to(ROOT)} and {TOOLS_DOC_PATH.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
